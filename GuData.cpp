// 生成资料库补充条目。idBase 避开手工精编条目已占用的 id。
std::vector<GuTemplate> buildCanonGuData(std::uint32_t idBase) {
    std::vector<GuTemplate> v;
    v.reserve(567);
    GuId id = static_cast<GuId>(idBase);
    for (const auto& r : kGuRaw) {
        GuTemplate g;
        g.id            = id++;
        g.name          = r.name;
        g.rank          = static_cast<Rank>(r.rank);
        g.rankConfirmed = r.rankConfirmed;
        g.dao           = r.dao;
        g.category      = r.cat;
        g.effect        = r.eff;
        g.feed          = r.mat;
        g.source        = r.src;
        g.original      = false;
        v.push_back(std::move(g));
    }
    return v;
}

