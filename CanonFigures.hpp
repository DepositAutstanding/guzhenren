// 是否与原著人物同名（去空白后比较，忽略大小写）
inline bool isCanonFigureName(std::string n) {
    // 去空白
    std::string t;
    for (char c : n) {
        if (!std::isspace(static_cast<unsigned char>(c))) t.push_back(c);
    }
    if (t.empty()) return false;
    for (const auto& f : canonFigureNames()) {
        if (t == f) return true;
    }
    return false;
}

